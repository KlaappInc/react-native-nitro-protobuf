// Signature stamped onto every file this generator emits (nitrogen/margelo style).
function signedHeader(filename, p = '//') {
  return [
    p,
    `${p} ${filename}`,
    `${p} This file was generated by react-native-nitro-protobuf. DO NOT MODIFY THIS FILE.`,
    `${p} https://github.com/KlaappInc/react-native-nitro-protobuf`,
    `${p} Copyright © Thomas Roux @ Klaapp (https://klaapp.io)`,
    p,
  ].join('\n')
}

function findExecutable(name) {
  const exts =
    process.platform === 'win32' ? ['.exe', '.cmd', '.bat', ''] : ['']
  for (const dir of (process.env.PATH ?? '').split(path.delimiter)) {
    for (const ext of exts) {
      const candidate = path.join(dir, name + ext)
      if (fs.existsSync(candidate)) return candidate
    }
  }
  return null
}

function venvBinDir(venv) {
  return path.join(venv, process.platform === 'win32' ? 'Scripts' : 'bin')
}

// protoc: explicit flag/env -> grpc-tools bundle -> system protoc.
function resolveProtoc(args) {
  if (args.protoc) return args.protoc
  if (process.env.PROTOC) return process.env.PROTOC
  try {
    const require = createRequire(import.meta.url)
    const pkg = require.resolve('grpc-tools/package.json')
    const bin = path.join(
      path.dirname(pkg),
      'bin',
      process.platform === 'win32' ? 'protoc.exe' : 'protoc'
    )
    if (fs.existsSync(bin)) return bin
  } catch {
    // grpc-tools not installed; fall through to system protoc.
  }
  const system = findExecutable('protoc')
  if (system) return system
  throw new Error(
    'protoc not found. Reinstall dependencies (grpc-tools provides a bundled ' +
      'protoc) or pass --protoc <path>.'
  )
}

// nanopb plugin: explicit flag/env -> cached venv -> bootstrap (python3 + pip).
function resolveNanopbPlugin(args) {
  if (args.nanopb) return args.nanopb
  if (process.env.NANOPB_PLUGIN) return process.env.NANOPB_PLUGIN
  if (process.env.NANOPB_PROTOC_GEN) return process.env.NANOPB_PROTOC_GEN

  const cacheDir = path.join(moduleRoot, '.cache')
  const venv = path.join(cacheDir, 'nanopb-venv')
  const pluginName =
    process.platform === 'win32' ? 'protoc-gen-nanopb.exe' : 'protoc-gen-nanopb'
  const plugin = path.join(venvBinDir(venv), pluginName)
  if (fs.existsSync(plugin)) return plugin

  const python = findExecutable('python3') ?? findExecutable('python')
  if (!python) {
    throw new Error(
      'The nanopb code generator is missing and python3 (needed once to install ' +
        'it) was not found. Install python3, or install nanopb yourself and pass ' +
        '--nanopb <path to protoc-gen-nanopb>.'
    )
  }

  console.error(
    `[nitro-protobuf] Installing nanopb ${NANOPB_VERSION} generator (one-time setup)…`
  )
  fs.mkdirSync(cacheDir, { recursive: true })
  execFileSync(python, ['-m', 'venv', venv], { stdio: 'inherit' })
  const pip = path.join(
    venvBinDir(venv),
    process.platform === 'win32' ? 'pip.exe' : 'pip'
  )
  execFileSync(pip, ['install', '--quiet', `nanopb==${NANOPB_VERSION}`], {
    stdio: 'inherit',
  })
  if (!fs.existsSync(plugin)) {
    throw new Error(
      'nanopb bootstrap failed: protoc-gen-nanopb not found after install.'
    )
  }
  return plugin
}

// The grpc-tools-bundled protoc ships the well-known-type protos under
// <grpc-tools>/bin/google/protobuf/*.proto. Returns that include root (the dir
// that contains `google/`) so `import "google/protobuf/timestamp.proto"` works.
function wktIncludeDir() {
  try {
    const require = createRequire(import.meta.url)
    const pkg = require.resolve('grpc-tools/package.json')
    const dir = path.join(path.dirname(pkg), 'bin')
    if (
      fs.existsSync(path.join(dir, 'google', 'protobuf', 'timestamp.proto'))
    ) {
      return dir
    }
  } catch {
    // grpc-tools unavailable; WKT imports must be resolvable another way.
  }
  return null
}

// Scan the given .proto files for `import "google/protobuf/X.proto"` and return
// the absolute paths of the imported WKT files (so nanopb also generates them).
function collectWktImports(protoFiles, wktDir) {
  const found = new Set()
  if (!wktDir) return []
  for (const file of protoFiles) {
    let text = ''
    try {
      text = fs.readFileSync(file, 'utf8')
    } catch {
      continue
    }
    for (const m of text.matchAll(
      /import\s+(?:public\s+)?"(google\/protobuf\/[^"]+)"/g
    )) {
      const abs = path.join(wktDir, m[1])
      if (fs.existsSync(abs)) found.add(abs)
    }
  }
  return [...found]
}

