function parseArgs(argv) {
  const args = { _: [], protoPath: [], skipProtoc: false }
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    if (arg === '--protoDir') {
      args.protoDir = argv[++i]
    } else if (arg === '--outDir') {
      args.outDir = argv[++i]
    } else if (arg === '--tsOut') {
      args.tsOut = argv[++i]
    } else if (arg === '--protoPath') {
      args.protoPath.push(argv[++i])
    } else if (arg === '--protoc') {
      args.protoc = argv[++i]
    } else if (arg === '--nanopb' || arg === '--nanopbPlugin') {
      args.nanopb = argv[++i]
    } else if (arg === '--skipProtoc' || arg === '--skip-protoc') {
      args.skipProtoc = true
    } else if (arg === '--strict') {
      args.strict = true
    } else if (arg === '--watch' || arg === '-w') {
      args.watch = true
    } else if (arg === '--bigint') {
      args.bigint = true
    } else if (arg === '--enums') {
      args.enums = argv[++i] // 'string' | 'number'
    } else if (arg === '--help' || arg === '-h') {
      args.help = true
    } else {
      args._.push(arg)
    }
  }
  return args
}

function collectProtoFiles(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...collectProtoFiles(fullPath))
    } else if (entry.isFile() && entry.name.endsWith('.proto')) {
      files.push(fullPath)
    }
  }
  return files
}

function cppString(value) {
  // Escape backslashes first, then double quotes, for a C++ string literal.
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')
}

function mapFieldType(field) {
  if (field.resolvedType instanceof protobuf.Type) return 'Message'
  if (field.resolvedType instanceof protobuf.Enum) return 'Enum'
  switch (field.type) {
    case 'bool':
      return 'Bool'
    case 'int32':
      return 'Int32'
    case 'int64':
      return 'Int64'
    case 'uint32':
      return 'UInt32'
    case 'uint64':
      return 'UInt64'
    case 'sint32':
      return 'SInt32'
    case 'sint64':
      return 'SInt64'
    case 'fixed32':
      return 'Fixed32'
    case 'fixed64':
      return 'Fixed64'
    case 'sfixed32':
      return 'SFixed32'
    case 'sfixed64':
      return 'SFixed64'
    case 'float':
      return 'Float'
    case 'double':
      return 'Double'
    case 'string':
      return 'String'
    case 'bytes':
      return 'Bytes'
    default:
      throw new Error(`Unsupported field type: ${field.type}`)
  }
}

